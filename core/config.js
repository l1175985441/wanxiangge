/** 段名 → 组（⛔ 拿不到就给最后一组，别让它掉出左栏） */
export function groupOfSection(name) {
    const s = String(name || '');
    for (const g of SIDEBAR_GROUPS) {
        if (g.match.some((k) => s.includes(k))) {
            return g;
        }
    }
    return SIDEBAR_GROUPS[SIDEBAR_GROUPS.length - 1];
}

